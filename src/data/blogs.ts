export function getBlogBySlug(slug: string): BlogPost | undefined {
  return BLOG_POSTS.find((post) => post.slug === slug);
}

export function getBlogsByCategory(category: string): BlogPost[] {
  return BLOG_POSTS.filter((post) => post.category === category);
}

export function getFeaturedBlogs(): BlogPost[] {
  return BLOG_POSTS.filter((post) => post.featured);
}

export function getRelatedBlogs(currentSlug: string, limit: number = 3): BlogPost[] {
  const currentPost = getBlogBySlug(currentSlug);
  if (!currentPost) return [];

  // Get related posts by IDs first
  const relatedByIds = BLOG_POSTS.filter((post) => currentPost.relatedPosts.includes(post.slug));

  // If we need more, get posts from same category
  if (relatedByIds.length < limit) {
    const sameCategory = BLOG_POSTS.filter(
      (post) => post.category === currentPost.category && post.slug !== currentSlug && !relatedByIds.includes(post)
    );
    return [...relatedByIds, ...sameCategory].slice(0, limit);
  }

  return relatedByIds.slice(0, limit);
}
